import * as path from "node:path";
import * as fs from "node:fs/promises";
import type { ApiRouteIR, QueueConsumerIR } from "./types";

export class EntrypointGenerator {
  constructor(public readonly workDir: string) {}

  public async generateApi(api: ApiRouteIR): Promise<string> {
    const entryDir = path.join(this.workDir, ".syncploy", "entrypoints");
    await fs.mkdir(entryDir, { recursive: true });

    const entryFilePath = path.join(entryDir, `${api.id}.ts`);
    const importPath = api.sourceFile.replace(/\.[^/.]+$/, "");

    const code = `// Auto-generated by Syncploy. Do not edit.
import { ${api.exportName} as endpoint } from ${JSON.stringify(importPath)};

export async function handler(event: any) {
  try {
    const pathParams = event.pathParameters || {};
    const queryParams = event.queryStringParameters || {};
    const headers = event.headers || {};

    let body: any = {};
    if (event.body) {
      try {
        const rawBody = event.isBase64Encoded
          ? Buffer.from(event.body, "base64").toString("utf-8")
          : event.body;
        body = JSON.parse(rawBody);
      } catch {
        body = event.body;
      }
    }

    const req = {
      ...queryParams,
      ...pathParams,
      ...(typeof body === "object" && body !== null ? body : { body }),
    };

    const ctx = {
      headers,
      pathParameters: pathParams,
      queryStringParameters: queryParams,
      rawEvent: event,
    };

    const result = await endpoint.handler(req, ctx);

    return {
      statusCode: 200,
      headers: {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
        "Access-Control-Allow-Methods": "*",
        "Access-Control-Allow-Headers": "*",
      },
      body: JSON.stringify(result !== undefined ? result : null),
    };
  } catch (error: any) {
    console.error("[Syncploy Handler Error]:", error);
    const statusCode = error.statusCode || 500;
    return {
      statusCode,
      headers: {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
      },
      body: JSON.stringify({
        error: error.name || "Error",
        message: error.message || "Internal Server Error",
      }),
    };
  }
}
`;

    await fs.writeFile(entryFilePath, code, "utf-8");
    return entryFilePath;
  }

  public async generateConsumer(consumer: QueueConsumerIR): Promise<string> {
    const entryDir = path.join(this.workDir, ".syncploy", "entrypoints");
    await fs.mkdir(entryDir, { recursive: true });

    const entryFilePath = path.join(entryDir, `${consumer.id}.ts`);
    const importPath = consumer.sourceFile.replace(/\.[^/.]+$/, "");

    const code = `// Auto-generated by Syncploy. Do not edit.
import { ${consumer.exportName} as consumer } from ${JSON.stringify(importPath)};

export async function handler(event: any) {
  const batchItemFailures = [];
  const records = event.Records || [];

  for (const record of records) {
    try {
      let body = record.body;
      try {
        body = JSON.parse(record.body);
      } catch {}

      await consumer.handler(body);
    } catch (err) {
      console.error("[Syncploy Queue Consumer Error]:", err);
      batchItemFailures.push({ itemIdentifier: record.messageId });
    }
  }

  return { batchItemFailures };
}
`;

    await fs.writeFile(entryFilePath, code, "utf-8");
    return entryFilePath;
  }
}
