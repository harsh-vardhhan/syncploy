import * as path from "node:path";
import * as fs from "node:fs/promises";
import type {
  ApiRouteIR,
  QueueConsumerIR,
  TableStreamConsumerIR,
  TopicSubscriberIR,
} from "./types";

export class EntrypointGenerator {
  constructor(public readonly workDir: string) {}

  public async generateApi(api: ApiRouteIR): Promise<string> {
    const entryDir = path.join(this.workDir, ".syncploy", "entrypoints");
    await fs.mkdir(entryDir, { recursive: true });

    const entryFilePath = path.join(entryDir, `${api.id}.ts`);
    const importPath = api.sourceFile.replace(/\.[^/.]+$/, "");

    const code = `// Auto-generated by Syncploy. Do not edit.
import { ${api.exportName} as endpoint } from ${JSON.stringify(importPath)};

export async function handler(event: any) {
  try {
    const pathParams = event.pathParameters || {};
    const queryParams = event.queryStringParameters || {};
    const headers = event.headers || {};

    let body: any = {};
    if (event.body) {
      try {
        const rawBody = event.isBase64Encoded
          ? Buffer.from(event.body, "base64").toString("utf-8")
          : event.body;
        body = JSON.parse(rawBody);
      } catch {
        body = event.body;
      }
    }

    const req = {
      ...queryParams,
      ...pathParams,
      ...(typeof body === "object" && body !== null ? body : { body }),
    };

    const rawPath = event.rawPath || event.path || "/";
    const rawQueryString = event.rawQueryString || "";
    const method = event.requestContext?.http?.method || event.httpMethod || "GET";
    const host = headers.host || "localhost";
    const protocol = headers["x-forwarded-proto"] || "https";
    const fullUrl = protocol + "://" + host + rawPath + (rawQueryString ? "?" + rawQueryString : "");

    let webRequest: any;
    try {
      webRequest = new Request(fullUrl, {
        method,
        headers: new Headers(headers as Record<string, string>),
        body: ["GET", "HEAD"].includes(method)
          ? undefined
          : event.isBase64Encoded
            ? Buffer.from(event.body || "", "base64")
            : event.body,
      });
    } catch {
      webRequest = undefined;
    }

    const ctx = {
      headers,
      pathParameters: pathParams,
      queryStringParameters: queryParams,
      rawPath,
      rawQueryString,
      method,
      request: webRequest,
      rawEvent: event,
    };

    const result = await endpoint.handler(req, ctx);

    // If result is a Web standard Response object (e.g. Elysia or fetch)
    if (result && typeof result === "object" && typeof result.text === "function" && typeof result.status === "number") {
      const responseBody = await result.text();
      const responseHeaders: Record<string, string> = {};
      if (result.headers && typeof result.headers.forEach === "function") {
        result.headers.forEach((val: string, key: string) => {
          responseHeaders[key] = val;
        });
      }
      return {
        statusCode: result.status,
        headers: responseHeaders,
        body: responseBody,
      };
    }

    // If result is already a Lambda response object with statusCode
    if (result && typeof result === "object" && typeof result.statusCode === "number") {
      return result;
    }

    return {
      statusCode: 200,
      headers: {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
        "Access-Control-Allow-Methods": "*",
        "Access-Control-Allow-Headers": "*",
      },
      body: JSON.stringify(result !== undefined ? result : null),
    };
  } catch (error: any) {
    console.error("[Syncploy Handler Error]:", error);
    const statusCode = error.statusCode || 500;
    return {
      statusCode,
      headers: {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
      },
      body: JSON.stringify({
        error: error.name || "Error",
        message: error.message || "Internal Server Error",
      }),
    };
  }
}
`;

    await fs.writeFile(entryFilePath, code, "utf-8");
    return entryFilePath;
  }

  public async generateConsumer(consumer: QueueConsumerIR): Promise<string> {
    const entryDir = path.join(this.workDir, ".syncploy", "entrypoints");
    await fs.mkdir(entryDir, { recursive: true });

    const entryFilePath = path.join(entryDir, `${consumer.id}.ts`);
    const importPath = consumer.sourceFile.replace(/\.[^/.]+$/, "");

    const code = `// Auto-generated by Syncploy. Do not edit.
import { ${consumer.exportName} as consumer } from ${JSON.stringify(importPath)};

export async function handler(event: any) {
  const batchItemFailures = [];
  const records = event.Records || [];

  for (const record of records) {
    try {
      let body = record.body;
      try {
        body = JSON.parse(record.body);
      } catch {}

      await consumer.handler(body, { record, event });
    } catch (err) {
      console.error("[Syncploy Queue Consumer Error]:", err);
      batchItemFailures.push({ itemIdentifier: record.messageId });
    }
  }

  return { batchItemFailures };
}
`;

    await fs.writeFile(entryFilePath, code, "utf-8");
    return entryFilePath;
  }

  public async generateTableStream(consumer: TableStreamConsumerIR): Promise<string> {
    const entryDir = path.join(this.workDir, ".syncploy", "entrypoints");
    await fs.mkdir(entryDir, { recursive: true });

    const entryFilePath = path.join(entryDir, `${consumer.id}.ts`);
    const importPath = consumer.sourceFile.replace(/\.[^/.]+$/, "");

    const code = `// Auto-generated by Syncploy. Do not edit.
import { ${consumer.exportName} as streamConsumer } from ${JSON.stringify(importPath)};

export async function handler(event: any) {
  const batchItemFailures = [];
  const records = event.Records || [];

  for (const record of records) {
    try {
      await streamConsumer.handler(record, { event, record });
    } catch (err) {
      console.error("[Syncploy DynamoDB Stream Consumer Error]:", err);
      const seqNumber = record.dynamodb?.SequenceNumber;
      if (seqNumber) {
        batchItemFailures.push({ itemIdentifier: seqNumber });
      }
    }
  }

  return { batchItemFailures };
}
`;

    await fs.writeFile(entryFilePath, code, "utf-8");
    return entryFilePath;
  }

  public async generateTopicSubscriber(subscriber: TopicSubscriberIR): Promise<string> {
    const entryDir = path.join(this.workDir, ".syncploy", "entrypoints");
    await fs.mkdir(entryDir, { recursive: true });

    const entryFilePath = path.join(entryDir, `${subscriber.id}.ts`);
    const importPath = subscriber.sourceFile.replace(/\.[^/.]+$/, "");

    const code = `// Auto-generated by Syncploy. Do not edit.
import { ${subscriber.exportName} as subscriber } from ${JSON.stringify(importPath)};

export async function handler(event: any) {
  const records = event.Records || [];

  for (const record of records) {
    try {
      let message = record.Sns?.Message;
      try {
        message = JSON.parse(message);
      } catch {}

      await subscriber.handler(message, { record, event });
    } catch (err) {
      console.error("[Syncploy Topic Subscriber Error]:", err);
      throw err;
    }
  }
}
`;

    await fs.writeFile(entryFilePath, code, "utf-8");
    return entryFilePath;
  }
}
