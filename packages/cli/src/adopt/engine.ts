import * as fs from 'node:fs';
import * as path from 'node:path';
import { loadTemplate } from '../diff';
import type { AdoptOptions, AdoptResult } from './types';
import { parseSamConfig } from './config';
import { toVarName } from './resolvers';
import {
  type TranslatorContext,
  translateTables,
  translateBuckets,
  translateQueues,
  translateTopics,
  translateDeliveryStreams,
  translateAlarms,
  translateAuth,
  translateFunctions,
  extractUnmodeledResources,
} from './translators';

export function adoptTemplate(options: AdoptOptions): AdoptResult {
  const templatePath = path.resolve(process.cwd(), options.templatePath);
  if (!fs.existsSync(templatePath)) {
    throw new Error(`Template file not found at: ${templatePath}`);
  }

  let params: Record<string, string> = { ...(options.params || {}) };
  if (options.config) {
    const configPath = path.resolve(process.cwd(), options.config);
    const samConfig = parseSamConfig(configPath);
    params = { ...samConfig.parameters, ...params };
  }

  const template = loadTemplate(templatePath);
  const templateParams = template.Parameters || {};
  const resources = template.Resources || {};

  const adopted: AdoptResult["adoptedResources"] = {
    tables: [],
    buckets: [],
    queues: [],
    topics: [],
    deliveryStreams: [],
    alarms: [],
    functions: [],
    auths: [],
  };

  const codeBlocks: string[] = [];
  const bucketLogicalIdToVar: Record<string, string> = {};

  // First pass: identify buckets so delivery streams can reference them
  for (const [key, res] of Object.entries<any>(resources)) {
    if (res.Type === "AWS::S3::Bucket") {
      bucketLogicalIdToVar[key] = toVarName(key);
    }
  }

  const ctx: TranslatorContext = {
    resources,
    params,
    templateParams,
    bucketLogicalIdToVar,
  };

  const translators = [
    { target: adopted.tables, fn: translateTables },
    { target: adopted.buckets, fn: translateBuckets },
    { target: adopted.queues, fn: translateQueues },
    { target: adopted.topics, fn: translateTopics },
    { target: adopted.deliveryStreams, fn: translateDeliveryStreams },
    { target: adopted.alarms, fn: translateAlarms },
    { target: adopted.auths, fn: translateAuth },
    { target: adopted.functions, fn: translateFunctions },
  ];

  for (const { target, fn } of translators) {
    const res = fn(ctx);
    target.push(...res.adopted);
    if (res.code) {
      codeBlocks.push(res.code);
    }
  }

  const unmodeledResources = extractUnmodeledResources(resources);

  // Header and imports
  const header = [
    `// ============================================================================`,
    `// Auto-generated by Syncploy Adopt`,
    `// Source: ${path.relative(process.cwd(), templatePath)}`,
    `// Generated At: ${new Date().toISOString()}`,
    `// ============================================================================`,
    `import { Table, Bucket, Queue, Topic, Alarm, DeliveryStream, Auth } from "@syncploy/sdk";`,
    ``,
  ].join("\n");

  const fullCode = header + codeBlocks.join("\n\n") + "\n";

  if (options.out) {
    const outPath = path.resolve(process.cwd(), options.out);
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, fullCode, "utf-8");
  }

  return {
    code: fullCode,
    adoptedResources: adopted,
    unmodeledResources,
  };
}
